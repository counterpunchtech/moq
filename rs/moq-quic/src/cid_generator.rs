use std::hash::Hasher;

use rand::{Rng, RngExt};

use crate::Duration;
use crate::MAX_CID_SIZE;
use crate::shared::ConnectionId;

/// Generates connection IDs for incoming connections
pub trait ConnectionIdGenerator: Send + Sync {
    /// Generates a new CID
    ///
    /// Connection IDs MUST NOT contain any information that can be used by
    /// an external observer (that is, one that does not cooperate with the
    /// issuer) to correlate them with other connection IDs for the same
    /// connection. They MUST have high entropy, e.g. due to encrypted data
    /// or cryptographic-grade random data.
    fn generate_cid(&mut self) -> ConnectionId;

    /// Quickly determine whether `cid` could have been generated by this generator
    ///
    /// False positives are permitted, but increase the cost of handling invalid packets.
    fn validate(&self, _cid: ConnectionId) -> Result<(), InvalidCid> {
        Ok(())
    }

    /// Returns the length of a CID for connections created by this generator
    fn cid_len(&self) -> usize;
    /// Returns the lifetime of generated Connection IDs
    ///
    /// Connection IDs will be retired after the returned `Duration`, if any. Assumed to be constant.
    fn cid_lifetime(&self) -> Option<Duration>;
}

/// The connection ID was not recognized by the [`ConnectionIdGenerator`]
#[derive(Debug, Copy, Clone)]
pub struct InvalidCid;

/// Generates purely random connection IDs of a specified length
///
/// Random CIDs can be smaller than those produced by [`HashedConnectionIdGenerator`], but cannot be
/// usefully [`validate`](ConnectionIdGenerator::validate)d.
#[derive(Debug, Clone, Copy)]
pub struct RandomConnectionIdGenerator {
    cid_len: usize,
    lifetime: Option<Duration>,
}

impl Default for RandomConnectionIdGenerator {
    fn default() -> Self {
        Self {
            cid_len: 8,
            lifetime: None,
        }
    }
}

impl RandomConnectionIdGenerator {
    /// Initialize Random CID generator with a fixed CID length
    ///
    /// The given length must be less than or equal to MAX_CID_SIZE.
    pub fn new(cid_len: usize) -> Self {
        debug_assert!(cid_len <= MAX_CID_SIZE);
        Self {
            cid_len,
            ..Self::default()
        }
    }

    /// Set the lifetime of CIDs created by this generator
    pub fn set_lifetime(&mut self, d: Duration) -> &mut Self {
        self.lifetime = Some(d);
        self
    }
}

impl ConnectionIdGenerator for RandomConnectionIdGenerator {
    fn generate_cid(&mut self) -> ConnectionId {
        let mut bytes_arr = [0; MAX_CID_SIZE];
        rand::rng().fill_bytes(&mut bytes_arr[..self.cid_len]);

        ConnectionId::new(&bytes_arr[..self.cid_len])
    }

    /// Provide the length of dst_cid in short header packet
    fn cid_len(&self) -> usize {
        self.cid_len
    }

    fn cid_lifetime(&self) -> Option<Duration> {
        self.lifetime
    }
}

/// Generates 8-byte connection IDs that can be efficiently
/// [`validate`](ConnectionIdGenerator::validate)d
///
/// This generator uses a non-cryptographic hash and can therefore still be spoofed, but nonetheless
/// helps prevents Quinn from responding to non-QUIC packets at very low cost.
pub struct HashedConnectionIdGenerator {
    key: u64,
    lifetime: Option<Duration>,
    shard: Option<Shard>,
}

/// One endpoint's slot in a group sharing a port, which its connection IDs name.
#[derive(Debug, Clone, Copy)]
struct Shard {
    index: u16,
    count: u16,
}

impl Shard {
    /// A first byte congruent to `index` modulo `count`, keeping as much of the byte random as
    /// the group size leaves: `256 / count` values.
    fn prefix(self) -> u8 {
        let count = u32::from(self.count);
        let stride = rand::rng().random_range(0..256 / count);
        (stride * count + u32::from(self.index)) as u8
    }

    fn owns(self, first: u8) -> bool {
        u16::from(first) % self.count == self.index
    }
}

impl HashedConnectionIdGenerator {
    /// Create a generator with a random key
    pub fn new() -> Self {
        Self::from_key(rand::rng().random())
    }

    /// Create a generator with a specific key
    ///
    /// Allows [`validate`](ConnectionIdGenerator::validate) to recognize a consistent set of
    /// connection IDs across restarts
    pub fn from_key(key: u64) -> Self {
        Self {
            key,
            lifetime: None,
            shard: None,
        }
    }

    /// Set the lifetime of CIDs created by this generator
    pub fn set_lifetime(&mut self, d: Duration) -> &mut Self {
        self.lifetime = Some(d);
        self
    }

    /// Name shard `index` of a `count`-endpoint group in the first byte of every CID
    ///
    /// The byte is congruent to `index` modulo `count`, so a `SO_REUSEPORT` steering filter that
    /// reduces a packet's first destination CID byte modulo the group size delivers it to the
    /// endpoint that issued the CID. The fourth byte also sets both bits of `0x18`, which overlay
    /// the reserved key-encryption pattern of an SRT data header, so the filter can tell a short
    /// header from another protocol sharing the port. [`validate`](ConnectionIdGenerator::validate)
    /// then also refuses another shard's CIDs, so a stray packet is dropped rather than answered
    /// with a stateless reset for a connection a sibling owns.
    ///
    /// Panics unless `index < count <= 256`: one byte cannot name more shards than that.
    pub fn set_shard(&mut self, index: u16, count: u16) -> &mut Self {
        assert!(
            index < count && count <= 256,
            "shard {index} of {count} cannot be named by one byte"
        );
        self.shard = Some(Shard { index, count });
        self
    }

    /// The keyed hash of `nonce`, carrying the shard marker in its first byte when sharded.
    fn signature(&self, nonce: &[u8]) -> [u8; SIGNATURE_LEN] {
        let mut hasher = rustc_hash::FxHasher::default();
        hasher.write_u64(self.key);
        hasher.write(nonce);
        let mut signature = [0; SIGNATURE_LEN];
        signature.copy_from_slice(&hasher.finish().to_le_bytes()[..SIGNATURE_LEN]);
        if self.shard.is_some() {
            signature[0] |= SHARD_MARKER;
        }
        signature
    }
}

impl Default for HashedConnectionIdGenerator {
    fn default() -> Self {
        Self::new()
    }
}

impl ConnectionIdGenerator for HashedConnectionIdGenerator {
    fn generate_cid(&mut self) -> ConnectionId {
        let mut bytes_arr = [0; NONCE_LEN + SIGNATURE_LEN];
        rand::rng().fill_bytes(&mut bytes_arr[..NONCE_LEN]);
        if let Some(shard) = self.shard {
            bytes_arr[0] = shard.prefix();
        }
        let signature = self.signature(&bytes_arr[..NONCE_LEN]);
        bytes_arr[NONCE_LEN..].copy_from_slice(&signature);
        ConnectionId::new(&bytes_arr)
    }

    fn validate(&self, cid: ConnectionId) -> Result<(), InvalidCid> {
        if let Some(shard) = self.shard
            && !cid.first().is_some_and(|&first| shard.owns(first))
        {
            return Err(InvalidCid);
        }
        let (nonce, signature) = cid.split_at(NONCE_LEN);
        match self.signature(nonce) == signature {
            true => Ok(()),
            false => Err(InvalidCid),
        }
    }

    fn cid_len(&self) -> usize {
        NONCE_LEN + SIGNATURE_LEN
    }

    fn cid_lifetime(&self) -> Option<Duration> {
        self.lifetime
    }
}

const NONCE_LEN: usize = 3; // Good for more than 16 million connections
const SIGNATURE_LEN: usize = 8 - NONCE_LEN; // 8-byte total CID length
/// Set in a sharded CID's fourth byte, the signature's first; see
/// [`HashedConnectionIdGenerator::set_shard`].
const SHARD_MARKER: u8 = 0x18;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn validate_keyed_cid() {
        let mut generator = HashedConnectionIdGenerator::new();
        let cid = generator.generate_cid();
        generator.validate(cid).unwrap();
    }

    /// The steering filter's only requirement: whatever first byte a shard issues reduces back
    /// to that shard, at every group size including the one-value-per-shard ceiling.
    #[test]
    fn a_shard_cid_names_its_shard() {
        for count in [1u16, 2, 3, 7, 8, 64, 255, 256] {
            for index in 0..count {
                let mut generator = HashedConnectionIdGenerator::new();
                generator.set_shard(index, count);
                for _ in 0..32 {
                    let cid = generator.generate_cid();
                    assert_eq!(cid.len(), generator.cid_len());
                    assert_eq!(u16::from(cid[0]) % count, index);
                    assert_eq!(cid[3] & 0x18, 0x18, "CID lacks the non-SRT marker");
                    generator.validate(cid).unwrap();
                }
            }
        }
    }

    /// A shard refuses a sibling's CIDs even under the same key, so a misrouted packet is dropped
    /// rather than reset.
    #[test]
    fn a_shard_refuses_a_sibling_cid() {
        let mut first = HashedConnectionIdGenerator::from_key(7);
        first.set_shard(0, 4);
        let mut second = HashedConnectionIdGenerator::from_key(7);
        second.set_shard(1, 4);
        let cid = second.generate_cid();
        second.validate(cid).unwrap();
        assert!(first.validate(cid).is_err());
    }

    #[test]
    #[should_panic]
    fn a_shard_past_the_group_is_refused() {
        HashedConnectionIdGenerator::new().set_shard(4, 4);
    }

    #[test]
    #[should_panic]
    fn a_group_past_one_byte_is_refused() {
        HashedConnectionIdGenerator::new().set_shard(0, 257);
    }
}
